export const DOCS = 'https://lsmp.gg/resources/api';

export function absLinks(md: string | undefined): string {
	return String(md ?? '')
		.replace(/\]\(#([^)\s]+)\)/g, `](${DOCS}#$1)`)
		.replace(/\]\(\/resources\//g, '](https://lsmp.gg/resources/');
}

export const comment = (md: string): string =>
	absLinks(md)
		.split('\n')
		.map((line) => `---${line}`.replace(/\s+$/, ''))
		.join('\n');

export const oneLine = (md: string | undefined): string => absLinks(md).replace(/\s*\n\s*/g, ' ').trim();

export const header = (title: string, source: string): string =>
	`---@meta\n\n-- ${title}\n-- Generated by lsmp-lua-vscode from ${source}.\n`;
